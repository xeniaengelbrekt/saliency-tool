const round = (v, d) => {
  const p = 10 ** d;
  return Math.round(v * p) / p;
};

/** 4 значащие цифры — лучше работает для значений с большим разбросом порядка. */
const sigfig = (v, n = 4) => {
  if (v === 0 || !isFinite(v)) return v;
  return Number(v.toPrecision(n));
};

/**
 * Универсальный форматтер метрик для UI (метрические карточки, эксплейнер, CSV).
 * Учитывает единицы (проценты), большой разброс шкалы (peak), nullable.
 */
export function formatMetric(key, value) {
  if (value == null) return '—';
  if (typeof value === 'number' && !isFinite(value)) return '—';
  if (key === 'spread_pct' || key === 'peak_x' || key === 'peak_y') {
    return `${value}%`;
  }
  if (key === 'peak') {
    const abs = Math.abs(value);
    if (abs === 0) return '0';
    if (abs >= 100000 || abs < 0.001) return value.toExponential(2);
    return String(value);
  }
  return String(value);
}

/**
 * Вычисляет mean, peak, entropy, center_bias, spread_pct, peak_x, peak_y
 * для карты sal (Float32Array, длина width*height, значения в [0, 1]).
 *
 * Замечание про peak. Спека пишет «peak = max(S)», но S после
 * нормализации всегда даёт max = 1.0 — метрика была бы константой.
 * Поэтому реально информативная пиковая салиентность — это
 * максимум сырой карты ДО нормализации (нормализатор сохраняет
 * это значение в свойстве sal.rawMax). Координаты пика (peak_x/y)
 * берём из нормированной карты — это та же позиция, что и у raw.
 */
export function computeMetrics(sal, width, height) {
  const N = sal.length;

  let sum = 0;
  let peakNormalized = -Infinity;
  let peakIdx = 0;
  let spreadCount = 0;

  for (let i = 0; i < N; i++) {
    const v = sal[i];
    sum += v;
    if (v > peakNormalized) { peakNormalized = v; peakIdx = i; }
    if (v > 0.5) spreadCount++;
  }

  // Реальный пик — из сырых данных, сохранённых нормализатором
  const peak = sal.rawMax !== undefined ? sal.rawMax : peakNormalized;

  const mean = sum / N;
  const peakX = (peakIdx % width) / width  * 100;
  const peakY = Math.floor(peakIdx / width) / height * 100;
  const spreadPct = (spreadCount / N) * 100;

  // Энтропия по гистограмме из 64 бинов
  const bins = 64;
  const hist = new Int32Array(bins);
  for (let i = 0; i < N; i++) {
    let b = (sal[i] * bins) | 0;
    if (b >= bins) b = bins - 1;
    else if (b < 0) b = 0;
    hist[b]++;
  }
  let entropy = 0;
  for (let i = 0; i < bins; i++) {
    if (hist[i] > 0) {
      const p = hist[i] / N;
      entropy -= p * Math.log2(p);
    }
  }

  // Center bias: μ_inner / μ_outer, inner radius = 0.7 * min(cx, cy)
  const cx = width / 2;
  const cy = height / 2;
  const innerR = 0.7 * Math.min(cx, cy);
  const innerR2 = innerR * innerR;
  let innerSum = 0, innerCnt = 0, outerSum = 0, outerCnt = 0;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const dx = x - cx;
      const dy = y - cy;
      const v = sal[y * width + x];
      if (dx * dx + dy * dy <= innerR2) {
        innerSum += v;
        innerCnt++;
      } else {
        outerSum += v;
        outerCnt++;
      }
    }
  }
  const innerMean = innerCnt > 0 ? innerSum / innerCnt : 0;
  const outerMean = outerCnt > 0 ? outerSum / outerCnt : 0;
  const centerBias = outerMean > 0 ? innerMean / outerMean : 0;

  return {
    mean:        round(mean, 4),
    peak:        sigfig(peak, 4),  // 4 значащие цифры — peak имеет большой разброс шкалы
    entropy:     round(entropy, 2),
    center_bias: round(centerBias, 2),
    spread_pct:  round(spreadPct, 2),
    peak_x:      round(peakX, 2),
    peak_y:      round(peakY, 2),
  };
}

