/** Сетка, на которую приводятся карты разного размера перед корреляцией. */
const CORR_GRID = 128;

/**
 * Корреляция Пирсона между двумя картами.
 * Если карты разного размера (разные пропорции изображений), обе
 * приводятся билинейно к общей сетке CORR_GRID×CORR_GRID — то есть
 * сравнение идёт в относительных координатах кадра (0–100 % по осям).
 */
export function pearsonR(A, B) {
  // Одинаковое число пикселей не значит одинаковую форму: 256×144 и 144×256
  // имеют одну длину, но это разные сетки — сравниваем по размерам, если они известны.
  const sameShape = A.length === B.length && (!A.width || !B.width || (A.width === B.width && A.height === B.height));
  if (!sameShape) {
    if (!A.width || !B.width) throw new Error('Длины массивов не совпадают');
    A = resampleMap(A, A.width, A.height, CORR_GRID, CORR_GRID);
    B = resampleMap(B, B.width, B.height, CORR_GRID, CORR_GRID);
  }
  const N = A.length;

  let sumA = 0, sumB = 0;
  for (let i = 0; i < N; i++) {
    sumA += A[i];
    sumB += B[i];
  }
  const muA = sumA / N;
  const muB = sumB / N;

  let num = 0, denA = 0, denB = 0;
  for (let i = 0; i < N; i++) {
    const da = A[i] - muA;
    const db = B[i] - muB;
    num  += da * db;
    denA += da * da;
    denB += db * db;
  }
  const den = Math.sqrt(denA * denB);
  return den === 0 ? 0 : num / den;
}
