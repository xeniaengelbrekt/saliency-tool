/** Корреляция Пирсона между двумя картами одинаковой длины. */
export function pearsonR(A, B) {
  const N = A.length;
  if (B.length !== N) throw new Error('Длины массивов не совпадают');

  let sumA = 0, sumB = 0;
  for (let i = 0; i < N; i++) {
    sumA += A[i];
    sumB += B[i];
  }
  const muA = sumA / N;
  const muB = sumB / N;

  let num = 0, denA = 0, denB = 0;
  for (let i = 0; i < N; i++) {
    const da = A[i] - muA;
    const db = B[i] - muB;
    num  += da * db;
    denA += da * da;
    denB += db * db;
  }
  const den = Math.sqrt(denA * denB);
  return den === 0 ? 0 : num / den;
}
