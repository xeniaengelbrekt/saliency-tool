import { resampleMap } from './algorithms/util.js';

const round = (v, d) => {
  const p = 10 ** d;
  return Math.round(v * p) / p;
};

/** 4 значащие цифры — лучше работает для значений с большим разбросом порядка. */
const sigfig = (v, n = 4) => {
  if (v === 0 || !isFinite(v)) return v;
  return Number(v.toPrecision(n));
};

/**
 * Универсальный форматтер метрик для UI (метрические карточки, эксплейнер, CSV).
 * Учитывает единицы (проценты), большой разброс шкалы (peak), nullable.
 */
export function formatMetric(key, value) {
  if (value == null) return '—';
  if (typeof value === 'number' && !isFinite(value)) return '—';
  if (key === 'spread_pct' || key === 'peak_x' || key === 'peak_y') {
    return `${value}%`;
  }
  if (key === 'peak') {
    const abs = Math.abs(value);
    if (abs === 0) return '0';
    if (abs >= 100000 || abs < 0.001) return value.toExponential(2);
    return String(value);
  }
  return String(value);
}

/**
 * Вычисляет mean, peak, entropy, center_bias, spread_pct, peak_x, peak_y
 * для карты sal (Float32Array, длина width*height, значения в [0, 1]).
 *
 * peak — максимум сырой карты ДО нормировки (sal.rawMax): после
 * нормировки максимум всегда 1.0 и метрика была бы константой.
 *
 * peak_x / peak_y — центр масс всех пикселей с максимальным значением
 * (при робастной нормировке вершина может быть «плато»), по центрам
 * пикселей: 0 % — левый/верхний край, 100 % — правый/нижний.
 *
 * center_bias — отношение средних внутри и вне центрального эллипса
 * с полуосями 0.7·(W/2) и 0.7·(H/2). Эллипс повторяет форму кадра,
 * поэтому доля «центра» одинакова (≈ 38.5 % площади) для любых пропорций.
 */
export function computeMetrics(sal, width, height) {
  width = width ?? sal.width;
  height = height ?? sal.height;
  const N = sal.length;

  let sum = 0;
  let peakNormalized = -Infinity;
  let spreadCount = 0;

  for (let i = 0; i < N; i++) {
    const v = sal[i];
    sum += v;
    if (v > peakNormalized) peakNormalized = v;
    if (v > 0.5) spreadCount++;
  }

  // Центр масс вершины (все пиксели, равные максимуму)
  let px = 0, py = 0, pc = 0;
  for (let i = 0; i < N; i++) {
    if (sal[i] === peakNormalized) {
      px += (i % width) + 0.5;
      py += Math.floor(i / width) + 0.5;
      pc++;
    }
  }

  // Реальный пик — из сырых данных, сохранённых нормализатором
  const peak = sal.rawMax !== undefined ? sal.rawMax : peakNormalized;

  const mean = sum / N;
  const peakX = pc ? (px / pc) / width * 100 : 50;
  const peakY = pc ? (py / pc) / height * 100 : 50;
  const spreadPct = (spreadCount / N) * 100;

  // Энтропия по гистограмме из 64 бинов
  const bins = 64;
  const hist = new Int32Array(bins);
  for (let i = 0; i < N; i++) {
    let b = (sal[i] * bins) | 0;
    if (b >= bins) b = bins - 1;
    else if (b < 0) b = 0;
    hist[b]++;
  }
  let entropy = 0;
  for (let i = 0; i < bins; i++) {
    if (hist[i] > 0) {
      const p = hist[i] / N;
      entropy -= p * Math.log2(p);
    }
  }

  // Center bias: μ_inner / μ_outer, эллипс с полуосями 0.7·cx и 0.7·cy
  const cx = width / 2;
  const cy = height / 2;
  const ax = 0.7 * cx;
  const ay = 0.7 * cy;
  let innerSum = 0, innerCnt = 0, outerSum = 0, outerCnt = 0;
  for (let y = 0; y < height; y++) {
    const dy = (y + 0.5 - cy) / ay;
    for (let x = 0; x < width; x++) {
      const dx = (x + 0.5 - cx) / ax;
      const v = sal[y * width + x];
      if (dx * dx + dy * dy <= 1) {
        innerSum += v;
        innerCnt++;
      } else {
        outerSum += v;
        outerCnt++;
      }
    }
  }
  const innerMean = innerCnt > 0 ? innerSum / innerCnt : 0;
  const outerMean = outerCnt > 0 ? outerSum / outerCnt : 0;
  const centerBias = outerMean > 0 ? innerMean / outerMean : 0;

  return {
    mean:        round(mean, 4),
    peak:        sigfig(peak, 4),  // 4 значащие цифры — peak имеет большой разброс шкалы
    entropy:     round(entropy, 2),
    center_bias: round(centerBias, 2),
    spread_pct:  round(spreadPct, 2),
    peak_x:      round(peakX, 2),
    peak_y:      round(peakY, 2),
  };
}

